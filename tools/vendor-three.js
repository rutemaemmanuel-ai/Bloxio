#!/usr/bin/env node
/**
 * Copies the parts of three.js that Bloxio Studio imports into vendor/three.
 *
 * The site is served as static files (no bundler), so browser bare specifiers
 * like "three/addons/loaders/GLTFLoader.js" must resolve through an import map
 * pointing at real files. node_modules is gitignored and blocked by .assetsignore,
 * so the needed files are vendored instead.
 *
 * Run after upgrading three:  npm run vendor:three
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const threeRoot = path.join(root, 'node_modules', 'three');
const outRoot = path.join(root, 'vendor', 'three');

// build/ is copied wholesale because three.module.js imports './three.core.js'.
const BUILD_FILES = ['three.module.js', 'three.core.js'];
// Addons kept in sync with the imports at the top of studio-engine.js,
// plus their own relative dependencies.
const ADDON_FILES = [
  'controls/OrbitControls.js',
  'controls/TransformControls.js',
  'loaders/GLTFLoader.js',
  'loaders/OBJLoader.js',
  'utils/BufferGeometryUtils.js',
  'utils/SkeletonUtils.js'
];

function main() {
  if (!fs.existsSync(threeRoot)) {
    console.error('three is not installed. Run: npm install --save-dev three');
    process.exitCode = 1;
    return;
  }

  const missing = [];
  const copies = [
    ...BUILD_FILES.map(file => [path.join(threeRoot, 'build', file), path.join(outRoot, file)]),
    ...ADDON_FILES.map(file => [
      path.join(threeRoot, 'examples', 'jsm', file),
      path.join(outRoot, 'addons', file)
    ])
  ];

  for (const [source, destination] of copies) {
    if (!fs.existsSync(source)) {
      missing.push(path.relative(root, source));
      continue;
    }
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(source, destination);
  }

  if (missing.length) {
    console.error(`Missing three.js files:\n  ${missing.join('\n  ')}`);
    process.exitCode = 1;
    return;
  }

  const version = require(path.join(threeRoot, 'package.json')).version;
  fs.writeFileSync(
    path.join(outRoot, 'VERSION'),
    `three@${version}\nGenerated by tools/vendor-three.js. Do not edit by hand.\n`
  );
  console.log(`Vendored three@${version} -> ${path.relative(root, outRoot)}`);
}

main();
